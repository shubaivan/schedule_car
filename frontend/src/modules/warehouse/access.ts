import { SessionExpired } from '../../app/api'

/** Форми складу для тих, кому склад відкрито лише на читання (продажі, бухгалтерія). */
export const READ_ONLY = 'Склад відкрито вам лише на читання: рухи й картки записують менеджер і адміністратор постачання або директор.'

/**
 * Чесна відповідь замість порожнього списку: склад бачать ті, хто його веде (менеджер
 * і адміністратор постачання, директор), а також продажі й бухгалтерія — на читання;
 * на стенді без складу (WAREHOUSE_ENABLED=0) його немає.
 * Інша помилка — '' (її показує звичайний банер).
 */
export function accessError(e: unknown): string {
    if (e instanceof SessionExpired || !(e instanceof Error)) return ''
    if (/\b403\b|Access Denied/i.test(e.message))
        return 'Склад бачать менеджер і адміністратор постачання, директор, менеджер з продажу й бухгалтер. Якщо вам потрібен доступ — попросіть адміністратора змінити роль.'
    if (/\b404\b/.test(e.message)) return 'На цьому стенді розділ «Склад» вимкнено.'
    return ''
}
