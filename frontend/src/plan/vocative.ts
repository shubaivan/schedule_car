/**
 * Кличний відмінок імені для звертання: «Добрий день, Іване / Олександре / Ірино».
 * Спершу словник поширених імен (там, де загальне правило помиляється: Ігор → Ігорю,
 * Олег → Олегу, Лев → Леве), далі прості правила за закінченням. Будь-що незвичне
 * (латиниця, подвійне імʼя, коротке) — як є: краще «Ivan», ніж зіпсоване імʼя.
 */
const EXCEPTIONS: Record<string, string> = {
    Ігор: 'Ігорю',
    Олег: 'Олегу',
    Лев: 'Леве',
    Любов: 'Любове',
    Яків: 'Якове',
    Григорій: 'Григорію',
    Ілля: 'Ілле',
    Микита: 'Микито',
    Кузьма: 'Кузьмо',
    Лука: 'Луко',
    Олекса: 'Олексо',
    Ольга: 'Ольго',
    Інна: 'Інно',
    Алла: 'Алло',
    Жанна: 'Жанно',
    Ганна: 'Ганно',
}

const NAME = /^[А-ЯІЇЄҐ][а-яіїєґ'ʼ]{2,}$/u
const FEMALE_CONSONANT = new Set(['Любов', 'Нінель', 'Агнес'])

export function vocative(name: string | null | undefined): string {
    const n = (name ?? '').trim()
    if (!NAME.test(n)) return n
    if (EXCEPTIONS[n]) return EXCEPTIONS[n]
    if (FEMALE_CONSONANT.has(n)) return n
    if (n.endsWith('ія')) return n.slice(0, -1) + 'є' // Марія → Маріє, Юлія → Юліє
    if (n.endsWith('ля') || n.endsWith('ня')) return n.slice(0, -1) + 'ю' // Оля → Олю, Таня → Таню
    if (n.endsWith('я')) return n.slice(0, -1) + 'ю' // Катя → Катю
    if (n.endsWith('а')) return n.slice(0, -1) + 'о' // Ірина → Ірино, Микола → Миколо
    if (n.endsWith('о')) return n.slice(0, -1) + 'е' // Дмитро → Дмитре, Павло → Павле
    if (n.endsWith('ій') || n.endsWith('й')) return n.slice(0, -1) + 'ю' // Сергій → Сергію
    if (n.endsWith('ь')) return n.slice(0, -1) + 'ю' // Василь → Василю
    if (/[гкх]$/.test(n)) return n + 'у' // Олег (словник), Ярик → Ярику
    if (/[бвдзлмнпрстфцчшщж]$/.test(n)) return n + 'е' // Іван → Іване, Олександр → Олександре
    return n
}
